# ============================================================
# CAREER ROADMAP
# ============================================================

class Roadmap(Base):
    __tablename__ = "roadmaps"

    id = Column(
        Integer,
        primary_key=True,
        index=True,
    )

    user_id = Column(
        Integer,
        ForeignKey("users.id"),
        nullable=False,
    )

    resume_id = Column(
        Integer,
        ForeignKey("resumes.id"),
        nullable=False,
    )

    job_id = Column(
        Integer,
        ForeignKey("job_descriptions.id"),
        nullable=False,
    )

    # Target job/role generated by AI
    target_role = Column(
        String(255),
        nullable=True,
    )

    # Overall AI readiness score
    readiness_score = Column(
        Integer,
        default=0,
    )

    # AI-generated roadmap summary
    summary = Column(
        Text,
        nullable=True,
    )

    # AI-generated insights stored as JSON string
    insights = Column(
        Text,
        nullable=True,
    )

    # AI-generated recommendations stored as JSON string
    recommendations = Column(
        Text,
        nullable=True,
    )

    created_at = Column(
        DateTime,
        default=lambda: datetime.now(timezone.utc),
    )

    updated_at = Column(
        DateTime,
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
    )


# ============================================================
# ROADMAP STAGE
# ============================================================

class RoadmapStage(Base):
    __tablename__ = "roadmap_stages"

    id = Column(
        Integer,
        primary_key=True,
        index=True,
    )

    roadmap_id = Column(
        Integer,
        ForeignKey("roadmaps.id"),
        nullable=False,
    )

    title = Column(
        String(255),
        nullable=False,
    )

    # completed / current / upcoming
    status = Column(
        String(50),
        nullable=False,
        default="upcoming",
    )

    duration_days = Column(
        Integer,
        default=7,
    )

    # Percentage from 0 to 100
    completion = Column(
        Integer,
        default=0,
    )

    # Controls stage ordering
    stage_order = Column(
        Integer,
        default=1,
    )


# ============================================================
# ROADMAP ITEM / TASK
# ============================================================

class RoadmapItem(Base):
    __tablename__ = "roadmap_items"

    id = Column(
        Integer,
        primary_key=True,
        index=True,
    )

    stage_id = Column(
        Integer,
        ForeignKey("roadmap_stages.id"),
        nullable=False,
    )

    # Task description
    label = Column(
        Text,
        nullable=False,
    )

    # 0 = incomplete, 1 = completed
    done = Column(
        Integer,
        default=0,
    )

    # Controls task ordering inside a stage
    item_order = Column(
        Integer,
        default=1,
    )